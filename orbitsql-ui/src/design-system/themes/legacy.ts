import type { Theme, ThemeColors, ThemeMode, ThemeSyntax } from "../types";

type LegacyColors = {
  bgPrimary: string;
  bgSecondary: string;
  bgElevated: string;
  bgSurface: string;
  accent: string;
  accentHover: string;
  accentMuted: string;
  success: string;
  warning: string;
  error: string;
  textPrimary: string;
  textSecondary: string;
  textMuted: string;
  border: string;
  borderSubtle: string;
  borderDefault: string;
  borderStrong: string;
  borderInput: string;
  borderFocus: string;
  borderDivider: string;
};

type LegacyThemeDefinition = {
  id: string;
  name: string;
  author: string;
  type: ThemeMode;
  colors: LegacyColors;
  syntax: ThemeSyntax;
};

function createLegacyTheme(definition: LegacyThemeDefinition): Theme {
  const { colors: legacy, syntax } = definition;
  const statusContainer = legacy.bgElevated;
  const colors: ThemeColors = {
    surface: legacy.bgPrimary,
    surfaceDim: legacy.bgSecondary,
    surfaceBright: legacy.bgElevated,
    surfaceContainerLowest: legacy.bgElevated,
    surfaceContainerLow: legacy.bgSecondary,
    surfaceContainer: legacy.bgElevated,
    surfaceContainerHigh: legacy.bgElevated,
    surfaceContainerHighest: legacy.bgSurface,
    onSurface: legacy.textPrimary,
    onSurfaceVariant: legacy.textSecondary,
    inverseSurface: legacy.textPrimary,
    inverseOnSurface: legacy.bgPrimary,
    outline: legacy.borderDefault,
    outlineVariant: legacy.borderSubtle,
    surfaceTint: legacy.accent,
    primary: legacy.accent,
    onPrimary: "#ffffff",
    primaryContainer: legacy.accentMuted,
    onPrimaryContainer: legacy.textPrimary,
    inversePrimary: legacy.accentHover,
    secondary: syntax.function,
    onSecondary: "#ffffff",
    secondaryContainer: syntax.table,
    onSecondaryContainer: legacy.textPrimary,
    tertiary: legacy.success,
    onTertiary: "#ffffff",
    tertiaryContainer: legacy.success,
    onTertiaryContainer: legacy.textPrimary,
    error: legacy.error,
    onError: "#ffffff",
    errorContainer: statusContainer,
    onErrorContainer: legacy.textPrimary,
    success: legacy.success,
    onSuccess: "#ffffff",
    successContainer: statusContainer,
    onSuccessContainer: legacy.textPrimary,
    warning: legacy.warning,
    onWarning: "#ffffff",
    warningContainer: statusContainer,
    onWarningContainer: legacy.textPrimary,
    primaryFixed: legacy.accentMuted,
    primaryFixedDim: legacy.accent,
    onPrimaryFixed: legacy.textPrimary,
    onPrimaryFixedVariant: legacy.textSecondary,
    secondaryFixed: syntax.function,
    secondaryFixedDim: syntax.table,
    onSecondaryFixed: legacy.textPrimary,
    onSecondaryFixedVariant: legacy.textSecondary,
    tertiaryFixed: legacy.success,
    tertiaryFixedDim: legacy.success,
    onTertiaryFixed: legacy.textPrimary,
    onTertiaryFixedVariant: legacy.textSecondary,
    background: legacy.bgPrimary,
    onBackground: legacy.textPrimary,
    surfaceVariant: legacy.bgSurface,
    syntax,
  };

  return {
    id: definition.id,
    name: definition.name,
    author: definition.author,
    type: definition.type,
    colors,
    typography: precisionTypography,
    radii: precisionRadii,
    spacing: precisionSpacing,
    elevation: precisionElevation,
  };
}

