function unique<T extends string>(values: readonly T[]): readonly T[] {
  return [...new Set(values)];
}

function createFunctionMap(
  definitions: readonly FunctionDefinition[],
): ReadonlyMap<
  string,
  Readonly<{
    name: string;
    returnFamily: SqlTypeFamily;
    argumentFamilies: readonly SqlTypeFamily[];
  }>
> {
  const functions = new Map<
    string,
    {
      name: string;
      returnFamily: SqlTypeFamily;
      argumentFamilies: readonly SqlTypeFamily[];
    }
  >();
  for (const [name, returnFamily, argumentFamilies] of definitions) {
    const normalizedName = name.toLocaleUpperCase();
    functions.set(normalizedName, {
      name: normalizedName,
      returnFamily,
      argumentFamilies,
    });
  }
  return functions;
}

function createDialect(
  id: DialectId,
  open: string,
  close: string,
  style: SqlDialect["quoting"]["style"],
  caseFold: SqlDialect["identifierRules"]["caseFold"],
  parameterStyle: SqlDialect["parameterStyle"],
  capabilities: Partial<SqlDialect["capabilities"]>,
  extraKeywords: readonly string[] = [],
  extraFunctions: readonly FunctionDefinition[] = [],
  extraOperators: readonly string[] = [],
  quoteStyles: readonly IdentifierQuoteStyle[] = [style],
): SqlDialect {
  return {
    id,
    codeMirrorDialect: id === "generic" ? "standard" : id,
    identifierRules: {
      quoteStyles: unique(quoteStyles),
      caseFold,
    },
    quoting: { open, close, style },
    keywords: new Set(
      unique(
        [...commonKeywords, ...extraKeywords].flatMap((value) =>
          value.split(/\s+/u),
        ),
      ).map((value) => value.toLocaleLowerCase()),
    ),
    functions: createFunctionMap([
      ...commonFunctionDefinitions,
      ...extraFunctions,
    ]),
    operators: unique([...commonOperators, ...extraOperators]),
    parameterStyle,
    capabilities: { ...baseCapabilities, ...capabilities },
  };
}

