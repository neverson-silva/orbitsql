export function getDialect(id: DialectId | string): SqlDialect {
  const dialect = dialectRegistry.get(id as DialectId);
  if (dialect) return dialect;
  const generic = dialectRegistry.get("generic");
  if (!generic) throw new Error("Generic dialect is not registered");
  return generic;
}

export function normalizeIdentifier(
  value: string,
  dialect: SqlDialect,
): string {
  const quoteStyle = detectQuoteStyle(value);
  const unquoted = quoteStyle
    ? unescapeQuotedIdentifier(value.slice(1, -1), quoteStyle)
    : value;
  if (quoteStyle) return unquoted;
  if (dialect.identifierRules.caseFold === "lower")
    return unquoted.toLocaleLowerCase();
  if (dialect.identifierRules.caseFold === "upper")
    return unquoted.toLocaleUpperCase();
  return unquoted;
}

export function quoteIdentifier(value: string, dialect: SqlDialect): string {
  const { open, close } = dialect.quoting;
  return `${open}${value.split(close).join(close + close)}${close}`;
}

export function isDialectKeyword(value: string, dialect: SqlDialect): boolean {
  return dialect.keywords.has(value.toLocaleLowerCase());
}

function detectQuoteStyle(value: string): IdentifierQuoteStyle | undefined {
  if (value.length < 2) return undefined;
  const pairs: readonly (readonly [string, string, IdentifierQuoteStyle])[] = [
    ['"', '"', "double"],
    ["`", "`", "backtick"],
    ["[", "]", "bracket"],
  ];
  for (const [open, close, style] of pairs) {
    if (value.startsWith(open) && value.endsWith(close)) return style;
  }
  return undefined;
}

function unescapeQuotedIdentifier(
  value: string,
  style: IdentifierQuoteStyle,
): string {
  const close = style === "bracket" ? "]" : style === "backtick" ? "`" : '"';
  return value.split(close + close).join(close);
}
