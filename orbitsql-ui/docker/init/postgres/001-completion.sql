CREATE TABLE completion_users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  status boolean NOT NULL DEFAULT true
);

CREATE TABLE completion_orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES completion_users(id),
  total numeric(12, 2) NOT NULL CHECK (total >= 0)
);

CREATE VIEW completion_users_view AS SELECT id, email, status FROM completion_users;
CREATE MATERIALIZED VIEW completion_orders_view AS SELECT id, user_id, total FROM completion_orders;
CREATE SEQUENCE completion_sequence;
CREATE TYPE completion_status AS ENUM ('active', 'inactive');
CREATE DOMAIN completion_domain AS text CHECK (length(VALUE) > 0);
CREATE TYPE completion_pair AS (left_value integer, right_value integer);
CREATE FUNCTION completion_identity(value text) RETURNS text LANGUAGE SQL AS 'SELECT value';
CREATE PROCEDURE completion_noop() LANGUAGE SQL AS 'SELECT 1';
